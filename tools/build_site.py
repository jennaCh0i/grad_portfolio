"""Build every page of the site from tools/content.py.

Run from the repo root:  python3 tools/build_site.py
"""
import html
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from content import ABOUT, CARDS, FILTERS, PROJECTS, SITE  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def esc(s):
    return html.escape(s, quote=True)


def head(title, desc, body_class):
    return f'''<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <meta name="theme-color" content="#f7f7f7" />
  <title>{esc(title)}</title>
  <meta name="description" content="{esc(desc[:155])}" />
  <link rel="preconnect" href="https://fonts.googleapis.com" />
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
  <link href="https://fonts.googleapis.com/css2?family=Fustat:wght@400;500;600&family=Newsreader:opsz,wght@6..72,300;6..72,400&display=swap" rel="stylesheet" />
  <link rel="stylesheet" href="/styles.css" />
</head>
<body class="{body_class}">
  <!-- Generated by tools/build_site.py from tools/content.py — edit content there, then re-run. -->
'''


TAIL = '''
  <script src="/main.js" defer></script>
</body>
</html>
'''

CLOCK = f'<p class="clock" data-clock data-tz="{SITE["timezone"]}" data-city="{SITE["city"]}">{SITE["city"]}.</p>'


# ---------------------------------------------------------------- media
def asset(slug, ref):
    kind, val = ref.split(":", 1)
    base = f"/assets/projects/{slug}"
    if kind == "i":
        ext = "gif" if os.path.exists(os.path.join(ROOT, f"assets/projects/{slug}/{val}.gif")) else "webp"
        return f'<img src="{base}/{val}.{ext}" alt="" loading="lazy" decoding="async" />'
    if kind == "v":
        return f'<video src="{base}/v{val}.mp4" autoplay muted loop playsinline preload="metadata"></video>'
    if kind == "vimeo":
        return (f'<div class="embed"><iframe src="https://player.vimeo.com/video/{val}?title=0&byline=0&portrait=0&dnt=1" '
                f'allow="autoplay; fullscreen; picture-in-picture" allowfullscreen loading="lazy" title="Video"></iframe></div>')
    if kind == "iframe":
        return f'<div class="embed embed--app"><iframe src="{esc(val)}" loading="lazy" title="Prototype"></iframe></div>'
    raise ValueError(ref)


def media(slug, item):
    ref, cap = item if isinstance(item, tuple) else (item, None)
    out = f'<figure class="fig">{asset(slug, ref)}'
    if cap:
        out += f"<figcaption>{esc(cap)}</figcaption>"
    return out + "</figure>"


def rows_html(slug, rows):
    return "\n".join(
        f'<div class="row row--{len(r)}">' + "".join(media(slug, i) for i in r) + "</div>" for r in rows)


# ---------------------------------------------------------------- home
def card(c, i):
    shape = c.get("shape", "wide")
    if c.get("video"):
        m = f'<video src="{c["video"]}" poster="/assets/work/{c["img"]}" autoplay muted loop playsinline preload="metadata"></video>'
    elif c.get("img"):
        m = f'<img src="/assets/work/{c["img"]}" alt="" loading="{"eager" if i < 2 else "lazy"}" />'
    else:
        m = f'<span class="card__fill" style="background:{c["fill"]}"></span>'
    title = esc(c["title"]) + (' <span class="card__ext" aria-hidden="true">↗</span>' if c.get("ext") else "")
    inner = (f'<div class="card__media card__media--{shape}">{m}</div>'
             f'<div class="card__cap"><p class="card__title">{title}</p><p class="card__year">{esc(c.get("year", ""))}</p></div>'
             f'<p class="card__desc">{esc(c["desc"])}</p>')
    cls = "card" + (" card--soon" if c.get("soon") else "")
    if c.get("href"):
        tgt = ' target="_blank" rel="noopener"' if c.get("ext") else ""
        inner = f'<a class="card__link" href="{c["href"]}"{tgt}>{inner}</a>'
    return f'      <article class="{cls}" data-tags="{c["tags"]}" style="--order:{i}">{inner}</article>'


def home():
    left = [card(c, i) for i, c in enumerate(CARDS) if i % 2 == 0]
    right = [card(c, i) for i, c in enumerate(CARDS) if i % 2 == 1]
    n = 0

    def num():
        nonlocal n
        n += 1
        return f"{n:02d}."

    index = "\n".join([
        f'        <a class="toc__item" href="/about"><span>{num()} About</span><span class="toc__arrow">→</span></a>',
        f'        <a class="toc__item" href="/fun"><span>{num()} Fun</span><span class="toc__arrow">→</span></a>',
    ])
    filters = "\n".join(
        f'        <button class="toc__item{" is-active" if k == "all" else ""}" data-filter="{k}" aria-pressed="{"true" if k == "all" else "false"}"><span>{num()} {esc(label)}</span></button>'
        for k, label in FILTERS)
    links = "\n".join(
        f'        <a class="toc__item" href="#" data-link="{k}"{"" if k == "email" else " target=\"_blank\" rel=\"noopener\""}><span>{num()} {label}</span><span class="toc__arrow">↗</span></a>'
        for k, label in [("email", "Email"), ("linkedin", "LinkedIn"), ("resume", "Résumé")])
    return head(f'{SITE["name"]} — Designer', SITE["bio"], "home") + f'''
  <header class="topbar">
    <a class="mark" href="/" aria-label="{SITE["name"]} — home"></a>
    {CLOCK}
  </header>

  <aside class="side">
    <div class="side__intro">
      <p>{esc(SITE["bio"])}</p>
      <p>{esc(SITE["currently"])}</p>
    </div>
    <nav class="toc" aria-label="Index">
      <p class="toc__head">Index</p>
{index}
      <p class="toc__head">Work</p>
      <div class="toc__group" role="toolbar" aria-label="Filter projects">
{filters}
      </div>
      <p class="toc__head">Links</p>
{links}
    </nav>
    <p class="side__foot">©2026 {SITE["name"]} <span class="side__sep">|</span> <span class="muted">Last updated {SITE["updated"]}</span></p>
  </aside>

  <main id="work" class="work" aria-label="Work">
    <div class="work__col">
{chr(10).join(left)}
    </div>
    <div class="work__col">
{chr(10).join(right)}
    </div>
  </main>

  <p class="signoff">{esc(SITE["signoff"])}</p>
''' + TAIL


# ---------------------------------------------------------------- article pages
def article_shell(title, desc, crumb, body):
    return head(title, desc, "article") + f'''
  <header class="art-top">
    <a class="back" href="/">← Back home</a>
    {CLOCK}
  </header>

  <main class="art">
    <p class="crumb"><a href="/">Home</a> <span>/</span> {esc(crumb)}</p>
{body}
  </main>

  <footer class="art-foot">
    <p>©2026 {SITE["name"]}</p>
    <p>{esc(SITE["signoff"])}</p>
  </footer>
''' + TAIL


def two(left, right, cls=""):
    return f'<div class="two{(" " + cls) if cls else ""}"><div class="two__l">{left}</div><div class="two__r">{right}</div></div>'


DIVIDER = '<div class="divider" aria-hidden="true"><span></span></div>'


def project(p, nxt):
    s = p["slug"]
    details = "".join(f"<p><span class=\"k\">{esc(k)}:</span> {v.replace('<br>', ', ')}</p>" for k, v in p["facts"])
    overview = f'<p>{esc(p["summary"])}</p>'
    if p.get("note"):
        overview += f'<p class="muted small">{esc(p["note"])}</p>'
    parts = [
        f'    <h1 class="art__title">{esc(p["title"])}</h1>',
        "    " + two(f'<p class="lbl">Details</p><p class="lbl-sub">{esc(p["meta"])}</p>{details}',
                    f'<p class="lbl">Overview</p>{overview}', "two--intro"),
        f'    <div class="hero">{media(s, p["hero"])}</div>',
    ]
    if p.get("deliverables"):
        parts.append("    " + DIVIDER)
        parts.append("    " + two('<p class="lbl">What I did</p><h2 class="art__h2">My deliverables</h2>',
                                  "<ol>" + "".join(f"<li>{esc(d)}</li>" for d in p["deliverables"]) + "</ol>"))
    parts.append("    " + DIVIDER)
    for sec in p["sections"]:
        left = (f'<p class="lbl">{esc(sec["label"])}</p><h2 class="art__h2">{esc(sec["heading"])}</h2>'
                if sec.get("heading") else f'<h2 class="art__h2">{esc(sec["label"])}</h2>')
        right = ""
        if sec.get("body"):
            right += f'<p>{esc(sec["body"])}</p>'
        if sec.get("flow"):
            right += '<p class="flowline">' + ' <span>→</span> '.join(esc(x) for x in sec["flow"]) + "</p>"
        if sec.get("facts"):
            right += "".join(f'<p><span class="k">{esc(k)}:</span> {v.replace("<br>", ", ")}</p>' for k, v in sec["facts"])
        if sec.get("link"):
            t, u = sec["link"]
            right += f'<p><a class="ulink" href="{esc(u)}" target="_blank" rel="noopener">{esc(t)}</a></p>'
        block = f'    <section class="asec" id="{sec["id"]}">\n      ' + two(left, right)
        if sec.get("rows"):
            block += "\n" + rows_html(s, sec["rows"])
        parts.append(block + "\n    </section>")
    parts.append("    " + DIVIDER)
    parts.append("    " + two(f'<p class="lbl">Next project</p><h2 class="art__h2"><a class="ulink" href="/{nxt["slug"]}">{esc(nxt["card"])} →</a></h2>',
                              '<p><a class="ulink" href="/">← Back to all work</a></p>', "two--next"))
    return article_shell(f'{p["card"]} — {SITE["name"]}', p["summary"], p["card"], "\n".join(parts))


def about():
    contact = "".join(
        f'<p><a class="ulink" href="#" data-link="{k}"{"" if k == "email" else " target=\"_blank\" rel=\"noopener\""}>{label} ↗</a></p>'
        for k, label in [("email", "Email"), ("linkedin", "LinkedIn"), ("resume", "Résumé")])
    parts = [f'    <h1 class="art__title">{esc(ABOUT["headline"])}</h1>',
             "    " + two(f'<p class="lbl">Contact</p>{contact}',
                         f'<p class="lbl">Overview</p><p>{esc(SITE["bio"])}</p><p>{esc(SITE["currently"])}</p>', "two--intro"),
             "    " + DIVIDER]
    for label, items in ABOUT["lists"]:
        rows = "".join(
            f'<li><span class="li__a">{esc(a)}</span><span class="li__b">{esc(b)}</span><span class="li__c">{esc(c)}</span></li>'
            for a, b, c in items)
        parts.append(f'    <section class="asec">' + two(f'<h2 class="art__h2">{esc(label)}</h2>', f'<ul class="plist">{rows}</ul>') + "</section>")
    return article_shell(f'About — {SITE["name"]}', SITE["bio"], "About", "\n".join(parts))


def fun():
    parts = ['    <h1 class="art__title">Playground</h1>',
             "    " + two('<p class="lbl">Overview</p>',
                         "<p>Side experiments in motion, type and interaction. Coming soon.</p>", "two--intro")]
    return article_shell(f'Fun — {SITE["name"]}', "Playground — coming soon.", "Fun", "\n".join(parts))


def write(name, text):
    with open(os.path.join(ROOT, name), "w") as f:
        f.write(text)
    print("wrote", name)


if __name__ == "__main__":
    write("index.html", home())
    write("about.html", about())
    write("fun.html", fun())
    for i, p in enumerate(PROJECTS):
        write(f'{p["slug"]}.html', project(p, PROJECTS[(i + 1) % len(PROJECTS)]))
